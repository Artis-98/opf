import { afterAll, describe, expect, it } from "vitest";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { strToU8, zipSync } from "fflate";
import { parseDuration, parseGcodeComments, readPlateFile } from "./plate-file";

const dir = mkdtempSync(join(tmpdir(), "opf-plate-"));
afterAll(() => rmSync(dir, { recursive: true, force: true }));

describe("parseDuration", () => {
  it("reads the ways slicers write time", () => {
    expect(parseDuration("1h 2m 3s")).toBe(3723);
    expect(parseDuration("1d 0h 5m")).toBe(86700);
    expect(parseDuration("45m 10s")).toBe(2710);
    expect(parseDuration("nothing")).toBeNull();
  });
});

describe("parseGcodeComments", () => {
  it("reads OrcaSlicer's header and footer", () => {
    const g = [
      "; HEADER_BLOCK_START",
      "; generated by OrcaSlicer 2.3.1 on 2026-10-14 at 10:00:00",
      "; model printing time: 1h 2m 3s; total estimated time: 1h 10m 3s",
      "; total layer number: 120",
      "; HEADER_BLOCK_END",
      "G28",
      "; filament used [mm] = 1234.5, 0.0, 410.2",
      "; filament used [g] = 3.70, 0.00, 1.23",
      "; total filament used [g] = 4.93",
      "; filament_colour = #FFFFFF;#000000;#00AE42",
      "; filament_type = PLA;PLA;PETG",
      "; printer_model = Bambu Lab A1",
    ].join("\n");
    expect(parseGcodeComments(g)).toEqual({
      minutes: 70,
      grams: 5,
      filaments: [
        { color: "#FFFFFF", material: "PLA", grams: 4 },
        { color: "#00AE42", material: "PETG", grams: 1 },
      ],
      slicedFor: "Bambu Lab A1",
    });
  });

  it("reads PrusaSlicer's footer", () => {
    const g = "G1 X1\n; filament used [g] = 12.34\n; estimated printing time (normal mode) = 2h 5m 0s\n; filament_type = PETG\n; filament_colour = #FF8000\n";
    expect(parseGcodeComments(g)).toEqual({ minutes: 125, grams: 12, filaments: [{ color: "#FF8000", material: "PETG", grams: 12 }], slicedFor: null });
  });

  it("refuses G-code that does not say how long it takes", () => {
    expect(() => parseGcodeComments("G28\nG1 X10\n")).toThrow(/how long/);
  });
});

describe("readPlateFile", () => {
  const info = (index: number, secs: number, grams: number) =>
    `<plate><metadata key="index" value="${index}"/><metadata key="prediction" value="${secs}"/><metadata key="weight" value="${grams}"/>` +
    `<filament id="1" type="PLA" color="#161616" used_g="${grams}"/></plate>`;

  it("reads the plate asked for from a two-plate .gcode.3mf, with its picture", async () => {
    const path = join(dir, "two.gcode.3mf");
    writeFileSync(path, zipSync({
      "Metadata/slice_info.config": strToU8(`<config>${info(1, 600, 3)}${info(2, 3600, 20)}</config>`),
      "Metadata/plate_1.gcode": strToU8("G28"),
      "Metadata/plate_2.gcode": strToU8("G28"),
      "Metadata/plate_2.png": new Uint8Array([137, 80, 78, 71]),
    }));
    const p2 = await readPlateFile(path, 2);
    expect(p2).toMatchObject({ minutes: 60, grams: 20, filaments: [{ color: "#161616", material: "PLA", grams: 20 }] });
    expect(p2.thumbnail).toMatch(/^data:image\/png;base64,/);
    expect((await readPlateFile(path, 1)).minutes).toBe(10);
  });

  it("refuses a plate that was not sliced", async () => {
    const path = join(dir, "unsliced.3mf");
    writeFileSync(path, zipSync({ "Metadata/slice_info.config": strToU8(`<config>${info(1, 600, 3)}</config>`), "3D/3dmodel.model": strToU8("<model/>") }));
    await expect(readPlateFile(path, 1)).rejects.toThrow(/not been sliced/);
  });

  it("reads plain G-code", async () => {
    const path = join(dir, "part.gcode");
    writeFileSync(path, "; estimated printing time (normal mode) = 30m 0s\nG28\n; total filament used [g] = 7.5\n");
    expect(await readPlateFile(path)).toMatchObject({ minutes: 30, grams: 8, thumbnail: null });
  });
});

describe("which printer a plate was sliced for", () => {
  it("reads it from G-code comments", () => {
    const g = "; total estimated time: 10m\n; printer_model = Bambu Lab A1 mini\n";
    expect(parseGcodeComments(g).slicedFor).toBe("Bambu Lab A1 mini");
    expect(parseGcodeComments("; total estimated time: 10m\n").slicedFor).toBeNull();
  });
});
